package com.energymonitor.notification.application.port.out;

import com.energymonitor.notification.domain.model.Notification;
import com.energymonitor.notification.domain.model.NotificationChannel;
import com.energymonitor.notification.domain.model.NotificationSourceType;
import java.time.LocalDateTime;
import java.util.List;
import java.util.Optional;

/**
 * Output port for the delivery log.
 *
 * <p>The transitions are separate methods rather than a single {@code save} so a caller cannot
 * write a row straight into {@code SENT} without going through the attempt, and so the
 * identifier is generated by the application layer rather than by the caller.
 *
 * <p>What is passed in is where the message came from and what wording was used, never the wording
 * itself. A password recovery code travels in the body of the message, and a port that accepted a
 * body would be a port through which a secret could reach a column.
 */
public interface NotificationRecordPort {

    /**
     * Opens a delivery log entry before the message is attempted.
     *
     * @param idNotification identifier generated by the caller
     * @param userId         the account the message is for
     * @param homeId         the home it concerns, optional
     * @param type           the context the message originates from
     * @param sourceId       the row in that context, optional
     * @param messageKey     stable name of the wording used
     * @param channel        delivery channel
     * @return the pending notification that was recorded
     */
    Notification openForSending(String idNotification, String userId, String homeId,
                                NotificationSourceType type, String sourceId, String messageKey,
                                NotificationChannel channel);

    /**
     * Closes the entry as delivered.
     *
     * @param idNotification identifier returned by {@link #openForSending}
     * @param sentAt        when the message left
     */
    void recordSent(String idNotification, LocalDateTime sentAt);

    /**
     * Closes the entry as failed.
     *
     * @param idNotification identifier returned by {@link #openForSending}
     * @param reason         why it did not go out
     */
    void recordFailure(String idNotification, String reason);

    /**
     * The entries still marked {@code PENDING} that were opened before a given instant.
     *
     * <p>Exists for the startup sweep. A row in this state whose delivery is no longer in flight
     * describes a send that a previous run started and never finished, and the only honest way to
     * close it is to admit it failed.
     *
     * @param openedBefore the cutoff, exclusive
     * @param limit        how many rows to return at once, so a large backlog cannot be loaded whole
     * @return the abandoned entries, oldest first
     */
    List<Notification> listPendingOpenedBefore(LocalDateTime openedBefore, int limit);

    /**
     * Closes every pending entry older than a cutoff as failed, in one statement.
     *
     * <p>Bulk rather than one call per row, and conditional on the row still being pending so a
     * delivery that completes while the sweep runs is not overwritten with a failure.
     *
     * @param openedBefore the cutoff, exclusive
     * @param reason       recorded on every row it closes
     * @return how many rows were closed
     */
    int failAbandoned(LocalDateTime openedBefore, String reason);

    /**
     * Looks up a single entry.
     *
     * @param idNotification identifier
     * @return the notification, or empty when no such row exists
     */
    Optional<Notification> findById(String idNotification);
}